import { z } from "zod";

function errorResult(text) {
  return { isError: true, content: [{ type: "text", text }] };
}

export function registerDocumentTools({ server, readIndexedResource }) {
  server.registerTool(
    "read_document",
    {
      title: "Read Document",
      description: [
        "Read the full text of a Dynamsoft documentation page by its doc:// URI.",
        "",
        "WHEN TO USE:",
        "- After search returns doc:// results whose matched passages do not cover the question: call read_document with the exact uri from a resource_link or the plain URI list before answering.",
        "- When you need the full article (complete API details, parameter lists, code with its original formatting) rather than a matched passage or summary.",
        "",
        "WHEN NOT TO USE:",
        "- When a matched passage returned by search already answers the question; cite that result's public URL instead.",
        "- For sample:// URIs, use get_sample_files with resource_uri instead (complete sample projects).",
        "- Do not construct or edit doc:// URIs yourself; they are generated by search and may change across data refreshes.",
        "",
        "PARAMETERS:",
        "- uri (required): The exact doc:// URI returned by search (e.g. a resource_link uri).",
        "",
        "RETURNS: The document as markdown text: title, public documentation URL (cite it in answers), and the full article body.",
        "On failure (stale or missing URI, unsupported version, unsupported scheme) returns isError with guidance; call search again to get a current URI.",
        "",
        "RELATED TOOLS: search (find doc:// URIs), get_sample_files (read sample:// projects), get_quickstart (starter code)."
      ].join("\n"),
      inputSchema: {
        uri: z.string().trim().min(1, "uri is required.").describe("Exact doc:// URI returned by search.")
      },
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: false
      }
    },
    async ({ uri }) => {
      const scheme = /^([a-z][a-z0-9+.-]*):\/\//i.exec(uri)?.[1]?.toLowerCase();
      if (scheme === "sample") {
        return errorResult(`read_document only reads doc:// URIs. For sample:// URIs, call get_sample_files with resource_uri="${uri}".`);
      }
      if (scheme !== "doc") {
        return errorResult(`Unsupported URI: "${uri}". read_document accepts only doc:// URIs returned by search.`);
      }

      let resource;
      try {
        resource = await readIndexedResource(uri);
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        return errorResult(`Failed to read document: ${message}`);
      }

      const text = typeof resource.text === "string" ? resource.text : "";
      if (!text.trim()) {
        return errorResult(`Document ${uri} has no readable text content. Call search again to find an alternative document.`);
      }

      return { content: [{ type: "text", text }] };
    }
  );
}
